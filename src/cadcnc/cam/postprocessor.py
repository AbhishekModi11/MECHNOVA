"""Post-processor converting validated ToolpathCollection into ISO standard CNC G-code."""

from datetime import datetime
from typing import Dict, List, Optional
from cadcnc.schemas.cam import ToolpathsCollection, MoveType, ToolpathOperation
from cadcnc.schemas.config import MachineConfig, ToolsDatabase

PROTOTYPE_WARNING_BANNER = """(****************************************************************)
(* WARNING: PROTOTYPE - NOT VERIFIED ON A MACHINE               *)
(* GENERATED BY CAD-CNC OPTIMIZATION ENGINE                     *)
(* DO NOT RUN ON A PRODUCTION CNC MACHINE WITHOUT SIMULATION     *)
(* AND CAREFUL DRY-RUN VERIFICATION                             *)
(****************************************************************)"""

class PostProcessor:
    """Generates standardized ISO/Fanuc G-code from validated toolpaths."""

    def __init__(self, machine_config: MachineConfig, tools_db: Optional[ToolsDatabase] = None):
        self.machine = machine_config.machine
        self.tools_db = tools_db
        self.tool_slots: Dict[str, int] = {}
        if tools_db:
            for idx, tool in enumerate(tools_db.tools, start=1):
                self.tool_slots[tool.id] = idx

    def get_tool_slot(self, tool_id: str) -> int:
        if tool_id in self.tool_slots:
            return self.tool_slots[tool_id]
        new_slot = len(self.tool_slots) + 1
        self.tool_slots[tool_id] = new_slot
        return new_slot

    def generate_gcode(self, toolpaths: ToolpathsCollection, program_number: int = 1001, setup_id: str = "SETUP-1") -> str:
        lines: List[str] = []

        # 1. Header
        lines.append("%")
        lines.append(f"O{program_number:04d} (CAD-CNC AUTO-GENERATED {setup_id})")
        lines.append(PROTOTYPE_WARNING_BANNER)
        lines.append(f"(MACHINE: {self.machine.name})")
        lines.append(f"(CONTROLLER: {self.machine.controller_flavor.upper()})")
        lines.append(f"(TOTAL OPERATIONS: {toolpaths.total_operations})")
        lines.append(f"(TOTAL MOVES: {toolpaths.total_moves})")
        lines.append("")

        # 2. Safety Preamble
        lines.append("(--- SAFETY PREAMBLE ---)")
        lines.append("G21 (Metric Units mm)")
        lines.append("G17 (XY Plane Selection)")
        lines.append("G90 (Absolute Distance Mode)")
        lines.append("G94 (Feed per Minute)")
        lines.append("G40 (Cutter Radius Comp Cancel)")
        lines.append("G49 (Tool Length Offset Cancel)")
        lines.append("G80 (Canned Cycle Cancel)")
        lines.append("G28 G91 Z0.0 (Safe Z Retract)")
        lines.append("G90")
        lines.append("")

        current_tool_id: Optional[str] = None

        # 3. Operations loop
        for op in toolpaths.operations:
            lines.append(f"(=== OP: {op.operation_id} | TOOL: {op.tool_name} ===)")

            # Tool Change if tool differs
            if op.tool_id != current_tool_id:
                current_tool_id = op.tool_id
                t_slot = self.get_tool_slot(op.tool_id)
                lines.append("M05 (Spindle Stop)")
                lines.append("G28 G91 Z0.0 (Retract for Tool Change)")
                lines.append("G90")
                lines.append(f"T{t_slot:02d} M06 (Load Tool {op.tool_id})")
                lines.append(f"S{round(op.spindle_rpm)} M03 (Spindle CW at {round(op.spindle_rpm)} RPM)")
                lines.append("G54 (Work Coordinate System 1)")
                lines.append(f"G43 H{t_slot:02d} (Tool Length Offset)")

            # Emit moves
            last_feed = None
            for move in op.moves:
                if move.move_type == MoveType.RAPID:
                    lines.append(f"G00 X{move.end.x:.3f} Y{move.end.y:.3f} Z{move.end.z:.3f}")
                elif move.move_type == MoveType.PLUNGE:
                    feed_str = f" F{move.feed_mm_min:.1f}" if move.feed_mm_min != last_feed else ""
                    last_feed = move.feed_mm_min
                    lines.append(f"G01 Z{move.end.z:.3f}{feed_str} (Plunge)")
                elif move.move_type == MoveType.CUT:
                    feed_str = f" F{move.feed_mm_min:.1f}" if move.feed_mm_min != last_feed else ""
                    last_feed = move.feed_mm_min
                    lines.append(f"G01 X{move.end.x:.3f} Y{move.end.y:.3f} Z{move.end.z:.3f}{feed_str}")
                elif move.move_type == MoveType.RETRACT:
                    lines.append(f"G00 Z{move.end.z:.3f} (Retract)")

            lines.append("")

        # 4. Program Footer
        lines.append("(--- PROGRAM FOOTER ---)")
        lines.append("M05 (Spindle Stop)")
        lines.append("M09 (Coolant Off)")
        lines.append("G28 G91 Z0.0 (Safe Z Retract)")
        lines.append("G28 Y0.0 (Table Present to Operator)")
        lines.append("G90")
        lines.append("M30 (Program End & Rewind)")
        lines.append("%")

        return "\n".join(lines) + "\n"
